fn main() {
    if let Err(error) = run() {
        eprintln!("xtask: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let args = env::args().skip(1).collect::<Vec<_>>();
    match args.as_slice() {
        [family, mode] if family == "capabilities" => capabilities(mode == "check" || mode == "--check"),
        [family, mode] if family == "guidance" && (mode == "generate" || mode == "check") => guidance(mode == "check"),
        [family, mode] if family == "release" && (mode == "check" || mode == "package") => release(mode),
        _ => Err("usage: cargo run --bin xtask -- capabilities generate|check | guidance generate|check | release check|package".to_owned()),
    }
}

fn capabilities(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let catalog_path = root.join("capabilities/catalog.json");
    let bytes = fs::read(&catalog_path).map_err(|error| error.to_string())?;
    let catalog: Value = serde_json::from_slice(&bytes).map_err(|error| error.to_string())?;
    let count = validate_catalog(&catalog)?;
    let hash = format!("{:x}", Sha256::digest(&bytes));
    let version = package_version(root)?;
    let records = catalog.as_array().expect("validated catalog array");
    let native_records = records
        .iter()
        .filter(|record| record["execution"] == "native")
        .collect::<Vec<_>>();
    let native_ids = native_records
        .iter()
        .enumerate()
        .map(|(index, record)| {
            format!(
                "    X(TEXT(\"{}\")){}\n",
                record["id"].as_str().unwrap(),
                if index + 1 == native_records.len() {
                    String::new()
                } else {
                    format!(" {}", '\\')
                }
            )
        })
        .collect::<String>();
    let public_operations = ["bridge.health", "bridge.describe"]
        .into_iter()
        .chain(
            native_records
                .iter()
                .map(|record| record["id"].as_str().unwrap()),
        )
        .chain(["editor.stop"])
        .collect::<Vec<_>>();
    let public_ids = public_operations
        .iter()
        .enumerate()
        .map(|(index, id)| {
            format!(
                "    X(TEXT(\"{id}\")){}\n",
                if index + 1 == public_operations.len() {
                    String::new()
                } else {
                    format!(" {}", '\\')
                }
            )
        })
        .collect::<String>();
    let invalid_fixtures = invalid_output_fixtures(&catalog);
    let invalid_compact =
        serde_json::to_string(&invalid_fixtures).map_err(|error| error.to_string())?;
    let invalid_json =
        serde_json::to_string_pretty(&invalid_fixtures).map_err(|error| error.to_string())? + "\n";
    let invalid_input_fixtures = invalid_input_fixtures(&catalog);
    let invalid_input_json = serde_json::to_string_pretty(&invalid_input_fixtures)
        .map_err(|error| error.to_string())?
        + "\n";
    let rust = format!(
        "// Generated by `cargo run --bin xtask -- capabilities generate`; do not edit.\npub const CATALOG_HASH: &str = \"{hash}\";\npub const CATALOG_COUNT: usize = {count};\npub const PLUGIN_VERSION: &str = \"{version}\";\n{}\n{}\n{}",
        rust_metadata(records),
        rust_validator(&catalog, "inputSchema", "validate_generated_input"),
        rust_validator(&catalog, "outputSchema", "validate_generated_output")
    );
    let header = format!(
        "#pragma once\n\n#define MAGI_AXI_VERSION TEXT(\"{version}\")\n#define MAGI_AXI_CATALOG_HASH TEXT(\"{hash}\")\n#define MAGI_AXI_CATALOG_COUNT {count}\n#define MAGI_AXI_NATIVE_CAPABILITY_COUNT {}\n#define MAGI_AXI_PUBLIC_OPERATION_COUNT {}\n#define MAGI_AXI_NATIVE_CAPABILITIES(X) \\\n++__NATIVE_IDS__\n#define MAGI_AXI_PUBLIC_OPERATIONS(X) \\\n++__PUBLIC_IDS__\n{}\n#define MAGI_AXI_INVALID_OUTPUT_FIXTURES_JSON TEXT({invalid_compact:?})\n\nstatic int32 MagiAxiUnicodeScalarCount(const FString& Text)\n{{\n    int32 Count = 0;\n    for (int32 Index = 0; Index < Text.Len(); ++Index, ++Count)\n    {{\n        const uint32 CodeUnit = static_cast<uint32>(Text[Index]);\n        if (CodeUnit >= 0xD800 && CodeUnit <= 0xDBFF && Index + 1 < Text.Len())\n        {{\n            const uint32 Next = static_cast<uint32>(Text[Index + 1]);\n            if (Next >= 0xDC00 && Next <= 0xDFFF) ++Index;\n        }}\n    }}\n    return Count;\n}}\n\n{}\n{}",
        native_records.len(),
        public_operations.len(),
        cpp_metadata(&native_records),
        cpp_validator(&catalog, "inputSchema", "MagiAxiValidateInput"),
        cpp_validator(&catalog, "outputSchema", "MagiAxiValidateOutput")
    )
    .replace("++__NATIVE_IDS__", &native_ids)
    .replace("++__PUBLIC_IDS__", &public_ids);
    let outputs = [
        (root.join("src/capability_generated.rs"), rust),
        (
            root.join(
                "plugin/MagiUnrealAXI/Source/MagiUnrealAXI/Public/MagiAxiCatalog.generated.h",
            ),
            header,
        ),
        (
            root.join("capabilities/output-invalid.generated.json"),
            invalid_json,
        ),
        (
            root.join("capabilities/input-invalid.generated.json"),
            invalid_input_json,
        ),
    ];
    for (path, expected) in outputs {
        if check {
            let actual = fs::read_to_string(&path).map_err(|error| error.to_string())?;
            if actual != expected {
                return Err(format!(
                    "generated artifact is stale: {}; run capabilities generate",
                    path.display()
                ));
            }
        } else {
            fs::write(&path, expected).map_err(|error| error.to_string())?;
        }
    }
    println!("capability catalog: {count} records, sha256:{hash}");
    Ok(())
}

fn guidance(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let source =
        fs::read_to_string(root.join("guidance/magi-unreal-axi.md")).map_err(|e| e.to_string())?;
    if !source.starts_with("# ") || !source.contains("## Non-interactive examples") {
        return Err("guidance source must contain title and non-interactive examples".into());
    }
    for marker in [
        "local",
        "available",
        "unavailable",
        "unknown",
        "editor_offline",
        "blueprint_compile_failed",
        "operation view",
        "do not automatically retry",
        "no rollback",
        "persistence claim",
    ] {
        if !source.contains(marker) {
            return Err(format!("guidance missing semantic marker: {marker}"));
        }
    }
    let examples = source
        .lines()
        .filter(|line| line.starts_with("magi-unreal-axi"))
        .collect::<Vec<_>>();
    if examples.len() < 5 || !source.contains("```sh") {
        return Err("guidance requires at least five CLI examples".into());
    }
    for example in &examples {
        let args = example.split_ascii_whitespace().collect::<Vec<_>>();
        Cli::try_parse_from(args)
            .map_err(|error| format!("guidance example does not parse: `{example}`: {error}"))?;
    }
    let generated = format!(
        "---\nname: magi-unreal-axi\ndescription: Use when an agent must inspect, mutate, save, run, build, test, cook, package, or diagnose an Unreal Engine project through the non-interactive magi-unreal-axi CLI. Not for non-Unreal work or general shell automation.\n---\n\n{}\n",
        source.trim_end()
    );
    let output = root.join("skills/magi-unreal-axi/SKILL.md");
    if check {
        if fs::read_to_string(&output).map_err(|e| e.to_string())? != generated {
            return Err("generated guidance is stale; run guidance generate".into());
        }
    } else {
        fs::create_dir_all(output.parent().unwrap()).map_err(|e| e.to_string())?;
        fs::write(output, generated).map_err(|e| e.to_string())?;
    }
    println!(
        "guidance: {} parser-tested CLI examples, trigger-shaped frontmatter",
        examples.len()
    );
    Ok(())
}

fn package_version(root: &Path) -> Result<String, String> {
    let cargo = fs::read_to_string(root.join("Cargo.toml")).map_err(|e| e.to_string())?;
    cargo
        .lines()
        .find_map(|line| {
            line.strip_prefix("version = ")
                .map(|v| v.trim_matches('"').to_owned())
        })
        .ok_or_else(|| "Cargo.toml version missing".into())
}

fn release(mode: &str) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let version = package_version(root)?;
    guidance(true)?;
    capabilities(true)?;
    let plugin: Value = serde_json::from_slice(
        &fs::read(root.join("plugin/MagiUnrealAXI/MagiUnrealAXI.uplugin"))
            .map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    if plugin["VersionName"].as_str() != Some(version.as_str()) {
        return Err("Cargo/plugin version mismatch".into());
    }
    for file in [
        "README.md",
        "LICENSE",
        "THIRD_PARTY_NOTICES.md",
        "CHANGELOG.md",
        "docs/engine-support.md",
        "docs/agent-evaluation.md",
        "skills/magi-unreal-axi/SKILL.md",
        "Cargo.lock",
    ] {
        if !root.join(file).is_file() {
            return Err(format!("required release file missing: {file}"));
        }
    }
    for file in [
        "README.md",
        "CHANGELOG.md",
        "PLAN.md",
        "docs/capabilities.md",
        "docs/contract.md",
        "docs/protocol.md",
        "docs/verification.md",
    ] {
        let contents = fs::read_to_string(root.join(file)).map_err(|error| error.to_string())?;
        if !contents.contains(CATALOG_HASH) {
            return Err(format!("documented catalog hash is stale: {file}"));
        }
    }
    if mode == "check" {
        println!("release: version {version}, matching native payload, required files present");
        return Ok(());
    }
    if std::env::consts::OS != "macos" || std::env::consts::ARCH != "aarch64" {
        return Err("release package supports only macOS arm64".into());
    }
    let release_dir = root.join("target/release");
    let binary = release_dir.join("magi-unreal-axi");
    if !binary.is_file() {
        return Err("target/release/magi-unreal-axi missing; build release first".into());
    }
    let package_name = format!("magi-unreal-axi-{version}-macos-arm64");
    let archive = release_dir.join(format!("{package_name}.tar.gz"));
    let staging = release_dir.join(&package_name);
    if staging.exists() {
        fs::remove_dir_all(&staging).map_err(|e| e.to_string())?;
    }
    if archive.exists() {
        fs::remove_file(&archive).map_err(|e| e.to_string())?;
    }
    fs::create_dir_all(staging.join("skills/magi-unreal-axi")).map_err(|e| e.to_string())?;
    fs::copy(&binary, staging.join("magi-unreal-axi")).map_err(|e| e.to_string())?;
    fs::copy(
        root.join("skills/magi-unreal-axi/SKILL.md"),
        staging.join("skills/magi-unreal-axi/SKILL.md"),
    )
    .map_err(|e| e.to_string())?;
    for file in [
        "README.md",
        "LICENSE",
        "THIRD_PARTY_NOTICES.md",
        "CHANGELOG.md",
        "Cargo.lock",
    ] {
        fs::copy(root.join(file), staging.join(file)).map_err(|e| e.to_string())?;
    }
    fs::create_dir_all(staging.join("docs")).map_err(|e| e.to_string())?;
    for file in ["engine-support.md", "agent-evaluation.md"] {
        fs::copy(
            root.join("docs").join(file),
            staging.join("docs").join(file),
        )
        .map_err(|e| e.to_string())?;
    }
    let status = Command::new("/usr/bin/tar")
        .args(["-czf"])
        .arg(&archive)
        .args(["-C"])
        .arg(&release_dir)
        .arg(&package_name)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("tar failed".into());
    }
    let digest = format!(
        "{:x}",
        Sha256::digest(fs::read(&archive).map_err(|e| e.to_string())?)
    );
    fs::write(
        release_dir.join("SHA256SUMS"),
        format!(
            "{digest}  {}\n",
            archive.file_name().unwrap().to_string_lossy()
        ),
    )
    .map_err(|e| e.to_string())?;
    fs::remove_dir_all(staging).map_err(|e| e.to_string())?;
    println!("release package: {} sha256:{digest}", archive.display());
    Ok(())
}

fn schema_types(schema: &Map<String, Value>) -> Vec<&str> {
    match schema.get("type") {
        Some(Value::String(value)) => vec![value],
        Some(Value::Array(values)) => values.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    }
}

fn minimal_value(schema: &Value) -> Value {
    let schema = schema.as_object().unwrap();
    let types = schema_types(schema);
    if types.contains(&"null") {
        return Value::Null;
    }
    match types.first().copied() {
        Some("object") => {
            let required = schema
                .get("required")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .collect::<HashSet<_>>();
            let values = schema["properties"]
                .as_object()
                .unwrap()
                .iter()
                .filter(|(name, _)| required.contains(name.as_str()))
                .map(|(name, child)| (name.clone(), minimal_value(child)))
                .collect();
            Value::Object(values)
        }
        Some("array") => {
            let count = schema.get("minItems").and_then(Value::as_u64).unwrap_or(0);
            Value::Array(
                (0..count)
                    .map(|_| minimal_value(&schema["items"]))
                    .collect(),
            )
        }
        Some("string") => {
            schema
                .get("enum")
                .and_then(Value::as_array)
                .and_then(|values| values.first())
                .cloned()
                .unwrap_or_else(|| {
                    Value::String("x".repeat(
                        schema.get("minLength").and_then(Value::as_u64).unwrap_or(0) as usize,
                    ))
                })
        }
        Some("integer") => {
            serde_json::json!(schema.get("minimum").and_then(Value::as_i64).unwrap_or(0))
        }
        Some("number") => {
            serde_json::json!(schema.get("minimum").and_then(Value::as_f64).unwrap_or(0.0))
        }
        Some("boolean") => Value::Bool(false),
        None if schema.get("variants").is_some() => {
            minimal_value(schema["variants"].as_array().unwrap().first().unwrap())
        }
        _ => unreachable!(),
    }
}

fn numeric_fixture_value(schema: &Value, below: bool) -> Option<Value> {
    let object = schema.as_object()?;
    let types = schema_types(object);
    if types.contains(&"integer") {
        let value = if below {
            object.get("minimum")?.as_i64()?.checked_sub(1)?
        } else {
            object.get("maximum")?.as_i64()?.checked_add(1)?
        };
        return Some(Value::Number(value.into()));
    }
    if types.contains(&"number") {
        let value = if below {
            object.get("minimum")?.as_f64()? - 1.0
        } else {
            object.get("maximum")?.as_f64()? + 1.0
        };
        return serde_json::Number::from_f64(value).map(Value::Number);
    }
    None
}

fn invalid_output_fixtures(catalog: &Value) -> Vec<Value> {
    let mut fixtures = Vec::new();
    for record in catalog.as_array().unwrap() {
        let id = record["id"].as_str().unwrap();
        let valid = minimal_value(&record["outputSchema"]);
        fixtures
            .push(serde_json::json!({"operation": id, "case": "missing-required", "result": {}}));
        let mut unknown = valid.clone();
        unknown
            .as_object_mut()
            .unwrap()
            .insert("unknown".into(), Value::Bool(true));
        fixtures.push(
            serde_json::json!({"operation": id, "case": "root-not-closed", "result": unknown}),
        );
        let mut number_paths = Vec::new();
        numeric_schema_paths(&record["outputSchema"], Vec::new(), &mut number_paths);
        for path in number_paths {
            let number_schema = schema_at_path(&record["outputSchema"], &path);
            let path_label = if path.is_empty() {
                "$".to_owned()
            } else {
                path.join(".")
            };
            for (suffix, below) in [("below-minimum", true), ("above-maximum", false)] {
                if let Some(value) = numeric_fixture_value(number_schema, below) {
                    let mut result = valid.clone();
                    set_schema_path(&mut result, &record["outputSchema"], &path, value);
                    fixtures.push(serde_json::json!({"operation":id,"case":format!("numeric-{suffix}@{path_label}"),"result":result}));
                }
            }
        }
    }

    let valid = |id: &str| {
        let record = catalog
            .as_array()
            .unwrap()
            .iter()
            .find(|record| record["id"] == id)
            .unwrap();
        minimal_value(&record["outputSchema"])
    };
    let mut missing_id = valid("actor.list");
    missing_id["count"] = serde_json::json!(1);
    missing_id["total"] = serde_json::json!(1);
    missing_id["items"] = serde_json::json!([{"label":"actor"}]);
    fixtures.push(
        serde_json::json!({"operation":"actor.list","case":"missing-list-id","result":missing_id}),
    );

    let mut nested_extra = valid("level.current");
    nested_extra["level"]
        .as_object_mut()
        .unwrap()
        .insert("unknown".into(), Value::Bool(true));
    fixtures.push(serde_json::json!({"operation":"level.current","case":"nested-not-closed","result":nested_extra}));

    let mut wrong_type = valid("editor.status");
    wrong_type["editorPid"] = Value::String("not-an-integer".into());
    fixtures.push(
        serde_json::json!({"operation":"editor.status","case":"wrong-type","result":wrong_type}),
    );

    let mut bad_enum = valid("editor.status");
    bad_enum["state"] = Value::String("invalid".into());
    fixtures.push(serde_json::json!({"operation":"editor.status","case":"enum","result":bad_enum}));

    let mut bad_bound = valid("actor.view");
    bad_bound["revision"] = Value::String("short".into());
    fixtures.push(
        serde_json::json!({"operation":"actor.view","case":"string-bound","result":bad_bound}),
    );

    let mut graph_rows = valid("blueprint.graph_view");
    graph_rows["items"] =
        serde_json::json!([{"graphId":"/Game/BP.BP:graph","kind":"ubergraph","name":"EventGraph"}]);
    fixtures.push(serde_json::json!({"operation":"blueprint.graph_view","case":"partial-graph-row","result":graph_rows}));
    let mut hybrid_rows = valid("blueprint.graph_view");
    hybrid_rows["items"] = serde_json::json!([{"graphId":"/Game/BP.BP:graph","kind":"ubergraph","name":"EventGraph","nodeCount":1,"nodeId":"node"}]);
    fixtures.push(serde_json::json!({"operation":"blueprint.graph_view","case":"hybrid-row","result":hybrid_rows}));
    let mut empty_rows = valid("blueprint.graph_view");
    empty_rows["items"] = serde_json::json!([{}]);
    fixtures.push(serde_json::json!({"operation":"blueprint.graph_view","case":"empty-row","result":empty_rows}));
    for (case, row) in [
        ("primitive-row", serde_json::json!(1)),
        ("null-row", Value::Null),
        ("array-row", serde_json::json!([])),
    ] {
        let mut invalid = valid("blueprint.graph_view");
        invalid["items"] = Value::Array(vec![row]);
        invalid["count"] = serde_json::json!(1);
        invalid["total"] = serde_json::json!(1);
        fixtures.push(
            serde_json::json!({"operation":"blueprint.graph_view","case":case,"result":invalid}),
        );
    }

    let mut bad_array_bound = valid("asset.list");
    bad_array_bound["items"] =
        Value::Array((0..101).map(|_| serde_json::json!({"id":"x"})).collect());
    fixtures.push(
        serde_json::json!({"operation":"asset.list","case":"array-bound","result":bad_array_bound}),
    );
    fixtures
}
fn invalid_input_fixtures(catalog: &Value) -> Vec<Value> {
    let mut fixtures = Vec::new();
    for record in catalog.as_array().unwrap() {
        let id = record["id"].as_str().unwrap();
        let schema = &record["inputSchema"];
        let valid = minimal_value(schema);
        let mut unknown = valid.clone();
        if let Some(object) = unknown.as_object_mut() {
            object.insert("unknown".into(), Value::Bool(true));
            fixtures.push(
                serde_json::json!({"operation":id,"case":"input-root-not-closed","args":unknown}),
            );
        }
        let mut number_paths = Vec::new();
        numeric_schema_paths(schema, Vec::new(), &mut number_paths);
        for path in number_paths {
            let number_schema = schema_at_path(schema, &path);
            let path_label = if path.is_empty() {
                "$".to_owned()
            } else {
                path.join(".")
            };
            for (suffix, below) in [("below-minimum", true), ("above-maximum", false)] {
                if let Some(value) = numeric_fixture_value(number_schema, below) {
                    let mut args = valid.clone();
                    set_schema_path(&mut args, schema, &path, value);
                    fixtures.push(serde_json::json!({"operation":id,"case":format!("numeric-{suffix}@{path_label}"),"args":args}));
                }
            }
        }
    }
    fixtures
}

fn numeric_schema_paths(schema: &Value, path: Vec<String>, paths: &mut Vec<Vec<String>>) {
    let Some(object) = schema.as_object() else {
        return;
    };
    if schema_types(object)
        .iter()
        .any(|kind| matches!(*kind, "integer" | "number"))
        && (object.contains_key("minimum") || object.contains_key("maximum"))
    {
        paths.push(path.clone());
    }
    if schema_types(object).contains(&"object")
        && let Some(properties) = object.get("properties").and_then(Value::as_object)
    {
        for (name, child) in properties {
            let mut child_path = path.clone();
            child_path.push(name.clone());
            numeric_schema_paths(child, child_path, paths);
        }
    }
    if schema_types(object).contains(&"array")
        && let Some(items) = object.get("items")
    {
        let mut child_path = path.clone();
        child_path.push("0".into());
        numeric_schema_paths(items, child_path, paths);
    }
    if let Some(variants) = object.get("variants").and_then(Value::as_array) {
        for (index, variant) in variants.iter().enumerate() {
            let mut variant_path = path.clone();
            variant_path.push(format!("@variant{index}"));
            numeric_schema_paths(variant, variant_path, paths);
        }
    }
}

fn schema_at_path<'a>(mut schema: &'a Value, path: &[String]) -> &'a Value {
    for part in path {
        schema = if let Some(index) = part.strip_prefix("@variant") {
            &schema["variants"][index.parse::<usize>().unwrap()]
        } else if part.parse::<usize>().is_ok() {
            &schema["items"]
        } else {
            &schema["properties"][part]
        };
    }
    schema
}

fn set_schema_path(value: &mut Value, schema: &Value, path: &[String], replacement: Value) {
    if path.is_empty() {
        *value = replacement;
        return;
    }
    if let Some(index) = path[0].strip_prefix("@variant") {
        let variant = &schema["variants"][index.parse::<usize>().unwrap()];
        *value = minimal_value(variant);
        set_schema_path(value, variant, &path[1..], replacement);
    } else if let Ok(index) = path[0].parse::<usize>() {
        let item_schema = &schema["items"];
        if !value.is_array() {
            *value = Value::Array(Vec::new());
        }
        let array = value.as_array_mut().unwrap();
        while array.len() <= index {
            array.push(minimal_value(item_schema));
        }
        set_schema_path(&mut array[index], item_schema, &path[1..], replacement);
    } else {
        let child_schema = &schema["properties"][&path[0]];
        if !value.is_object() {
            *value = Value::Object(Map::new());
        }
        let object = value.as_object_mut().unwrap();
        let child = object
            .entry(path[0].clone())
            .or_insert_with(|| minimal_value(child_schema));
        set_schema_path(child, child_schema, &path[1..], replacement);
    }
}

fn string_values(value: &Value) -> Vec<&str> {
    value
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect()
}

fn rust_slice(value: &Value) -> String {
    let values = string_values(value)
        .into_iter()
        .map(|value| format!("\"{value}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{values}]")
}

fn rust_option(value: Option<&str>) -> String {
    value.map_or_else(|| "None".to_owned(), |value| format!("Some(\"{value}\")"))
}

