fn rust_validator(catalog: &Value, schema_field: &str, function_name: &str) -> String {
    let mut output = format!(
        "pub fn {function_name}(id: &str, value: &serde_json::Value) -> Result<(), &'static str> {{\n    match id {{\n"
    );
    for record in catalog.as_array().unwrap() {
        let id = record["id"].as_str().unwrap();
        output.push_str(&format!("        \"{id}\" => {{\n"));
        let mut counter = 0;
        emit_rust_schema(
            &record[schema_field],
            "value",
            12,
            &mut counter,
            &mut output,
        );
        output.push_str("            Ok(())\n        }\n");
    }
    output.push_str("        _ => Err(\"unknown operation\"),\n    }\n}\n");
    output
}

fn emit_rust_schema(
    schema: &Value,
    value: &str,
    indent: usize,
    counter: &mut usize,
    output: &mut String,
) {
    let schema = schema.as_object().unwrap();
    let pad = " ".repeat(indent);
    if let Some(variants) = schema.get("variants").and_then(Value::as_array) {
        for (index, variant) in variants.iter().enumerate() {
            let condition = variants.iter().enumerate().flat_map(|(other_index, other)| {
                other["required"].as_array().into_iter().flatten().filter_map(Value::as_str).map(move |name| {
                    let present = other_index == index;
                    format!("{value}.as_object().is_some_and(|object| {}object.contains_key(\"{name}\"))", if present { "" } else { "!" })
                })
            }).collect::<Vec<_>>().join(" && ");
            let prefix = if index == 0 { "if" } else { "else if" };
            output.push_str(&format!("{pad}{prefix} {condition} {{\n"));
            emit_rust_schema(variant, value, indent + 4, counter, output);
            output.push_str(&format!("{pad}}} "));
        }
        output.push_str("else { return Err(\"output object does not match any variant\"); }\n");
        return;
    }
    let types = schema_types(schema);
    if types.contains(&"null") {
        output.push_str(&format!("{pad}if !{value}.is_null() {{\n"));
        emit_rust_non_null(schema, value, indent + 4, counter, output);
        output.push_str(&format!("{pad}}}\n"));
    } else {
        emit_rust_non_null(schema, value, indent, counter, output);
    }
}

fn emit_rust_non_null(
    schema: &Map<String, Value>,
    value: &str,
    indent: usize,
    counter: &mut usize,
    output: &mut String,
) {
    let types = schema_types(schema);
    let kind = types.iter().find(|kind| **kind != "null").unwrap();
    let pad = " ".repeat(indent);
    match *kind {
        "object" => {
            let index = *counter;
            *counter += 1;
            let object = format!("object_{index}");
            let properties = schema["properties"].as_object().unwrap();
            let allowed = properties
                .keys()
                .map(|name| format!("\"{name}\""))
                .collect::<Vec<_>>()
                .join(" | ");
            output.push_str(&format!(
                "{pad}let {object} = {value}.as_object().ok_or(\"output object expected\")?;\n"
            ));
            if properties.is_empty() {
                output.push_str(&format!(
                    "{pad}if !{object}.is_empty() {{ return Err(\"unknown output field\"); }}\n"
                ));
            } else {
                output.push_str(&format!("{pad}if {object}.keys().any(|key| !matches!(key.as_str(), {allowed})) {{ return Err(\"unknown output field\"); }}\n"));
            }
            let required = schema
                .get("required")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .collect::<HashSet<_>>();
            for (name, child) in properties {
                let child_index = *counter;
                *counter += 1;
                let child_value = format!("value_{child_index}");
                if required.contains(name.as_str()) {
                    output.push_str(&format!("{pad}let {child_value} = {object}.get(\"{name}\").ok_or(\"missing output field\")?;\n"));
                    emit_rust_schema(child, &child_value, indent, counter, output);
                } else {
                    output.push_str(&format!(
                        "{pad}if let Some({child_value}) = {object}.get(\"{name}\") {{\n"
                    ));
                    emit_rust_schema(child, &child_value, indent + 4, counter, output);
                    output.push_str(&format!("{pad}}}\n"));
                }
            }
        }
        "array" => {
            let index = *counter;
            *counter += 1;
            let array = format!("array_{index}");
            output.push_str(&format!(
                "{pad}let {array} = {value}.as_array().ok_or(\"output array expected\")?;\n"
            ));
            if let Some(minimum) = schema.get("minItems").and_then(Value::as_u64) {
                if minimum == 1 {
                    output.push_str(&format!("{pad}if {array}.is_empty() {{ return Err(\"output array below bound\"); }}\n"));
                } else {
                    output.push_str(&format!("{pad}if {array}.len() < {minimum} {{ return Err(\"output array below bound\"); }}\n"));
                }
            }
            let maximum = schema["maxItems"].as_u64().unwrap();
            output.push_str(&format!("{pad}if {array}.len() > {maximum} {{ return Err(\"output array exceeds bound\"); }}\n"));
            let item_index = *counter;
            *counter += 1;
            let item = format!("value_{item_index}");
            output.push_str(&format!("{pad}for {item} in {array} {{\n"));
            emit_rust_schema(&schema["items"], &item, indent + 4, counter, output);
            output.push_str(&format!("{pad}}}\n"));
        }
        "string" => {
            let index = *counter;
            *counter += 1;
            let text = format!("text_{index}");
            output.push_str(&format!(
                "{pad}let {text} = {value}.as_str().ok_or(\"output string expected\")?;\n"
            ));
            if let Some(minimum) = schema.get("minLength").and_then(Value::as_u64)
                && minimum > 0
            {
                output.push_str(&format!("{pad}if {text}.chars().count() < {minimum} {{ return Err(\"output string below bound\"); }}\n"));
            }
            let maximum = schema["maxLength"].as_u64().unwrap();
            output.push_str(&format!("{pad}if {text}.chars().count() > {maximum} {{ return Err(\"output string exceeds bound\"); }}\n"));
            if let Some(values) = schema.get("enum").and_then(Value::as_array) {
                let values = values
                    .iter()
                    .map(|value| format!("\"{}\"", value.as_str().unwrap()))
                    .collect::<Vec<_>>()
                    .join(" | ");
                output.push_str(&format!("{pad}if !matches!({text}, {values}) {{ return Err(\"output string is not in enum\"); }}\n"));
            }
        }
        "integer" => {
            let index = *counter;
            *counter += 1;
            let number = format!("number_{index}");
            output.push_str(&format!(
                "{pad}let {number} = {value}.as_i64().ok_or(\"output integer expected\")?;\n"
            ));
            if let Some(minimum) = schema.get("minimum").and_then(Value::as_i64) {
                output.push_str(&format!("{pad}if {number} < {minimum} {{ return Err(\"output integer below bound\"); }}\n"));
            }
            if let Some(maximum) = schema.get("maximum").and_then(Value::as_i64) {
                output.push_str(&format!("{pad}if {number} > {maximum} {{ return Err(\"output integer exceeds bound\"); }}\n"));
            }
        }
        "number" => {
            let index = *counter;
            *counter += 1;
            let number = format!("number_{index}");
            output.push_str(&format!(
                "{pad}let {number} = {value}.as_f64().filter(|number| number.is_finite()).ok_or(\"output number expected\")?;\n"
            ));
            if let Some(minimum) = schema.get("minimum").and_then(Value::as_f64) {
                output.push_str(&format!("{pad}if {number} < {minimum:?} {{ return Err(\"output number below bound\"); }}\n"));
            }
            if let Some(maximum) = schema.get("maximum").and_then(Value::as_f64) {
                output.push_str(&format!("{pad}if {number} > {maximum:?} {{ return Err(\"output number exceeds bound\"); }}\n"));
            }
        }
        "boolean" => output.push_str(&format!(
            "{pad}if !{value}.is_boolean() {{ return Err(\"output boolean expected\"); }}\n"
        )),
        _ => unreachable!(),
    }
}

fn cpp_validator(catalog: &Value, schema_field: &str, function_name: &str) -> String {
    let mut output = format!(
        "static bool {function_name}(const FString& Operation, const TSharedRef<FJsonObject>& Object)\n{{\n    const TSharedPtr<FJsonValue> Root = MakeShared<FJsonValueObject>(Object);\n"
    );
    for record in catalog.as_array().unwrap() {
        let id = record["id"].as_str().unwrap();
        output.push_str(&format!("    if (Operation == TEXT(\"{id}\"))\n    {{\n"));
        let mut counter = 0;
        emit_cpp_schema(&record[schema_field], "Root", 8, &mut counter, &mut output);
        output.push_str("        return true;\n    }\n");
    }
    output.push_str("    return false;\n}\n");
    output
}

fn emit_cpp_schema(
    schema: &Value,
    value: &str,
    indent: usize,
    counter: &mut usize,
    output: &mut String,
) {
    let schema = schema.as_object().unwrap();
    let pad = " ".repeat(indent);
    if let Some(variants) = schema.get("variants").and_then(Value::as_array) {
        output.push_str(&format!(
            "{pad}if (!{value}.IsValid() || {value}->Type != EJson::Object) return false;\n"
        ));
        for (index, variant) in variants.iter().enumerate() {
            let condition = variants
                .iter()
                .enumerate()
                .flat_map(|(other_index, other)| {
                    other["required"]
                        .as_array()
                        .into_iter()
                        .flatten()
                        .filter_map(Value::as_str)
                        .map(move |name| {
                            let present = other_index == index;
                            format!(
                                "{value}->AsObject()->HasField(TEXT(\"{name}\")) == {}",
                                if present { "true" } else { "false" }
                            )
                        })
                })
                .collect::<Vec<_>>()
                .join(" && ");
            let prefix = if index == 0 { "if" } else { "else if" };
            output.push_str(&format!("{pad}{prefix} ({condition})\n{pad}{{\n"));
            emit_cpp_schema(variant, value, indent + 4, counter, output);
            output.push_str(&format!("{pad}}}\n"));
        }
        output.push_str(&format!("{pad}else return false;\n"));
        return;
    }
    let types = schema_types(schema);
    if types.contains(&"null") {
        output.push_str(&format!(
            "{pad}if ({value}->Type != EJson::Null)\n{pad}{{\n"
        ));
        emit_cpp_non_null(schema, value, indent + 4, counter, output);
        output.push_str(&format!("{pad}}}\n"));
    } else {
        emit_cpp_non_null(schema, value, indent, counter, output);
    }
}

fn emit_cpp_non_null(
    schema: &Map<String, Value>,
    value: &str,
    indent: usize,
    counter: &mut usize,
    output: &mut String,
) {
    let types = schema_types(schema);
    let kind = types.iter().find(|kind| **kind != "null").unwrap();
    let pad = " ".repeat(indent);
    match *kind {
        "object" => {
            let index = *counter;
            *counter += 1;
            let object = format!("Object{index}");
            let properties = schema["properties"].as_object().unwrap();
            output.push_str(&format!("{pad}if (!{value}.IsValid() || {value}->Type != EJson::Object) return false;\n{pad}const TSharedPtr<FJsonObject> {object} = {value}->AsObject();\n"));
            let allowed = properties
                .keys()
                .map(|name| format!("Entry.Key != TEXT(\"{name}\")"))
                .collect::<Vec<_>>()
                .join(" && ");
            if properties.is_empty() {
                output.push_str(&format!(
                    "{pad}if (!{object}->Values.IsEmpty()) return false;\n"
                ));
            } else {
                output.push_str(&format!("{pad}for (const TPair<FString, TSharedPtr<FJsonValue>>& Entry : {object}->Values) if ({allowed}) return false;\n"));
            }
            let required = schema
                .get("required")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(Value::as_str)
                .collect::<HashSet<_>>();
            for (name, child) in properties {
                let child_index = *counter;
                *counter += 1;
                let child_value = format!("Value{child_index}");
                output.push_str(&format!("{pad}const TSharedPtr<FJsonValue> {child_value} = {object}->TryGetField(TEXT(\"{name}\"));\n"));
                if required.contains(name.as_str()) {
                    output.push_str(&format!(
                        "{pad}if (!{child_value}.IsValid()) return false;\n"
                    ));
                    emit_cpp_schema(child, &child_value, indent, counter, output);
                } else {
                    output.push_str(&format!("{pad}if ({child_value}.IsValid())\n{pad}{{\n"));
                    emit_cpp_schema(child, &child_value, indent + 4, counter, output);
                    output.push_str(&format!("{pad}}}\n"));
                }
            }
        }
        "array" => {
            let index = *counter;
            *counter += 1;
            let array = format!("Array{index}");
            output.push_str(&format!("{pad}if (!{value}.IsValid() || {value}->Type != EJson::Array) return false;\n{pad}const TArray<TSharedPtr<FJsonValue>>& {array} = {value}->AsArray();\n"));
            if let Some(minimum) = schema.get("minItems").and_then(Value::as_u64) {
                output.push_str(&format!(
                    "{pad}if ({array}.Num() < {minimum}) return false;\n"
                ));
            }
            output.push_str(&format!(
                "{pad}if ({array}.Num() > {}) return false;\n",
                schema["maxItems"].as_u64().unwrap()
            ));
            let item_index = *counter;
            *counter += 1;
            let item = format!("Value{item_index}");
            output.push_str(&format!(
                "{pad}for (const TSharedPtr<FJsonValue>& {item} : {array})\n{pad}{{\n"
            ));
            emit_cpp_schema(&schema["items"], &item, indent + 4, counter, output);
            output.push_str(&format!("{pad}}}\n"));
        }
        "string" => {
            let index = *counter;
            *counter += 1;
            let text = format!("Text{index}");
            output.push_str(&format!("{pad}if (!{value}.IsValid() || {value}->Type != EJson::String) return false;\n{pad}const FString {text} = {value}->AsString();\n"));
            if let Some(minimum) = schema.get("minLength").and_then(Value::as_u64) {
                output.push_str(&format!(
                    "{pad}if (MagiAxiUnicodeScalarCount({text}) < {minimum}) return false;\n"
                ));
            }
            output.push_str(&format!(
                "{pad}if (MagiAxiUnicodeScalarCount({text}) > {}) return false;\n",
                schema["maxLength"].as_u64().unwrap()
            ));
            if let Some(values) = schema.get("enum").and_then(Value::as_array) {
                let condition = values
                    .iter()
                    .map(|value| format!("{text} != TEXT(\"{}\")", value.as_str().unwrap()))
                    .collect::<Vec<_>>()
                    .join(" && ");
                output.push_str(&format!("{pad}if ({condition}) return false;\n"));
            }
        }
        "integer" | "number" => {
            let index = *counter;
            *counter += 1;
            let number = format!("Number{index}");
            output.push_str(&format!("{pad}double {number} = 0;\n{pad}if (!{value}.IsValid() || !{value}->TryGetNumber({number}) || !FMath::IsFinite({number})"));
            if *kind == "integer" {
                output.push_str(&format!(" || FMath::FloorToDouble({number}) != {number}"));
            }
            output.push_str(") return false;\n");
            if let Some(minimum) = schema.get("minimum").and_then(Value::as_f64) {
                output.push_str(&format!("{pad}if ({number} < {minimum:?}) return false;\n"));
            }
            if let Some(maximum) = schema.get("maximum").and_then(Value::as_f64) {
                output.push_str(&format!("{pad}if ({number} > {maximum:?}) return false;\n"));
            }
        }
        "boolean" => output.push_str(&format!(
            "{pad}if (!{value}.IsValid() || {value}->Type != EJson::Boolean) return false;\n"
        )),
        _ => unreachable!(),
    }
}

fn validate_catalog(catalog: &Value) -> Result<usize, String> {
    let records = catalog
        .as_array()
        .ok_or_else(|| "catalog root must be an array".to_owned())?;
    if records.is_empty() {
        return Err("catalog must not be empty".to_owned());
    }
    let mut seen = HashSet::new();
    for record in records {
        let object = record
            .as_object()
            .ok_or_else(|| "catalog records must be objects".to_owned())?;
        if let Some(field) = object
            .keys()
            .find(|field| !RECORD_FIELDS.contains(&field.as_str()))
        {
            return Err(format!("unknown capability field `{field}`"));
        }
        for field in RECORD_FIELDS {
            if !object.contains_key(*field) {
                return Err(format!("capability record is missing `{field}`"));
            }
        }
        let id = string(object, "id")?;
        if !valid_id(id) || !seen.insert(id) {
            return Err(format!("invalid or duplicate capability id `{id}`"));
        }
        let execution = object["execution"].as_str();
        let mutates = object["mutates"].as_bool();
        let destructive = object["destructive"].as_bool();
        let idempotency = object["idempotency"].as_str();
        let save_behavior = object["saveBehavior"].as_str();
        let transaction = object["transactionBehavior"].as_str();
        let reversibility = object["reversibility"].as_str();
        if object["version"].as_u64() != Some(1)
            || !matches!(execution, Some("local" | "native"))
            || mutates.is_none()
            || destructive.is_none()
            || !matches!(
                idempotency,
                Some("read-only" | "natural-key" | "request-key")
            )
            || !matches!(save_behavior, Some("none" | "dirty-only" | "explicit"))
            || !matches!(transaction, Some("none" | "atomic" | "non-atomic"))
            || !matches!(
                reversibility,
                Some("none" | "source-control" | "destructive")
            )
        {
            return Err(format!("{id}: invalid execution or safety metadata"));
        }
        let mutates = mutates.unwrap();
        let destructive = destructive.unwrap();
        if mutates == (idempotency == Some("read-only"))
            || (!mutates && transaction != Some("none"))
            || (!mutates && save_behavior != Some("none"))
            || (!mutates && reversibility != Some("none"))
        {
            return Err(format!(
                "{id}: read/mutation safety metadata is inconsistent"
            ));
        }
        if destructive
            && (!mutates
                || reversibility != Some("destructive")
                || object["inputSchema"]["properties"]["force"]["type"] != "boolean"
                || object["inputSchema"]["properties"]["dryRun"]["type"] != "boolean")
        {
            return Err(format!(
                "{id}: destructive operations require force, dryRun, and destructive reversibility"
            ));
        }
        validate_string_array(id, object, "allowedEditorStates", 8)?;
        validate_string_array(id, object, "requiresModules", 16)?;
        let states = string_values(&object["allowedEditorStates"]);
        if states.is_empty()
            || states
                .iter()
                .any(|state| !matches!(*state, "offline" | "editing" | "playing"))
            || (execution == Some("native") && states.contains(&"offline"))
        {
            return Err(format!("{id}: allowedEditorStates is invalid"));
        }
        validate_schema(id, &object["inputSchema"], 0)?;
        validate_schema(id, &object["outputSchema"], 0)?;
        let verification = object["verification"]
            .as_object()
            .ok_or_else(|| format!("{id}: verification must be an object"))?;
        const VERIFICATION_FIELDS: &[&str] = &[
            "failureReceipt",
            "identity",
            "persistence",
            "readback",
            "source",
            "targetFields",
            "thread",
        ];
        if let Some(field) = verification
            .keys()
            .find(|field| !VERIFICATION_FIELDS.contains(&field.as_str()))
        {
            return Err(format!("{id}: unknown verification field `{field}`"));
        }
        if mutates {
            let readback = verification
                .get("readback")
                .and_then(Value::as_str)
                .filter(|value| !value.is_empty())
                .ok_or_else(|| format!("{id}: mutations require verification.readback"))?;
            if readback != "artifact" && !valid_id(readback) {
                return Err(format!("{id}: verification.readback is invalid"));
            }
            let target_fields = verification
                .get("targetFields")
                .and_then(Value::as_array)
                .filter(|values| !values.is_empty() && values.len() <= 4)
                .ok_or_else(|| format!("{id}: mutations require bounded targetFields"))?;
            let output_properties = object["outputSchema"]["properties"]
                .as_object()
                .expect("validated root output object");
            let mut targets = HashSet::new();
            for target in target_fields {
                let target = target
                    .as_str()
                    .filter(|value| !value.is_empty())
                    .ok_or_else(|| format!("{id}: targetFields entries must be strings"))?;
                if !targets.insert(target)
                    || output_properties
                        .get(target)
                        .and_then(|schema| schema["type"].as_str())
                        != Some("string")
                {
                    return Err(format!(
                        "{id}: targetFields must identify unique string outputs"
                    ));
                }
            }
        } else if verification.contains_key("targetFields")
            || verification.contains_key("failureReceipt")
        {
            return Err(format!(
                "{id}: reads cannot declare mutation verification fields"
            ));
        }
        match verification.get("failureReceipt").and_then(Value::as_str) {
            None => {
                if transaction == Some("non-atomic") {
                    return Err(format!(
                        "{id}: non-atomic operations require failureReceipt"
                    ));
                }
            }
            Some("preserved-dirty") if mutates && transaction == Some("non-atomic") => {}
            Some(_) => return Err(format!("{id}: invalid failureReceipt contract")),
        }
        if !object["engineSupport"].is_object() {
            return Err(format!("{id}: engineSupport must be an object"));
        }
    }
    Ok(records.len())
}

fn validate_schema(id: &str, schema: &Value, depth: usize) -> Result<(), String> {
    if depth > 8 {
        return Err(format!("{id}: schema exceeds maximum depth"));
    }
    let object = schema
        .as_object()
        .ok_or_else(|| format!("{id}: schema must be an object"))?;
    const KEYS: &[&str] = &[
        "type",
        "additionalProperties",
        "properties",
        "required",
        "minimum",
        "maximum",
        "minLength",
        "maxLength",
        "minItems",
        "maxItems",
        "items",
        "enum",
        "default",
        "variants",
    ];
    if let Some(key) = object.keys().find(|key| !KEYS.contains(&key.as_str())) {
        return Err(format!("{id}: unsupported schema keyword `{key}`"));
    }
    if let Some(variants) = object.get("variants") {
        let variants = variants
            .as_array()
            .filter(|values| values.len() >= 2)
            .ok_or_else(|| format!("{id}: variants must contain at least two schemas"))?;
        for variant in variants {
            validate_schema(id, variant, depth + 1)?;
        }
        return Ok(());
    }
    let types = match object.get("type") {
        Some(Value::String(value)) => vec![value.as_str()],
        Some(Value::Array(values)) => values
            .iter()
            .map(|value| {
                value
                    .as_str()
                    .ok_or_else(|| format!("{id}: schema types must be strings"))
            })
            .collect::<Result<Vec<_>, _>>()?,
        _ => return Err(format!("{id}: schema type is required")),
    };
    if types.is_empty()
        || types.iter().any(|value| {
            !matches!(
                *value,
                "object" | "array" | "string" | "integer" | "number" | "boolean" | "null"
            )
        })
    {
        return Err(format!("{id}: unsupported schema type"));
    }
    if types.contains(&"object") {
        if object.get("additionalProperties") != Some(&Value::Bool(false)) {
            return Err(format!(
                "{id}: closed objects require additionalProperties false"
            ));
        }
        if let Some(properties) = object.get("properties").and_then(Value::as_object) {
            let required = object
                .get("required")
                .and_then(Value::as_array)
                .cloned()
                .unwrap_or_default();
            let mut seen = HashSet::new();
            for value in required {
                let name = value
                    .as_str()
                    .ok_or_else(|| format!("{id}: required names must be strings"))?;
                if !seen.insert(name.to_owned()) || !properties.contains_key(name) {
                    return Err(format!("{id}: required/property mismatch"));
                }
            }
            for property in properties.values() {
                validate_schema(id, property, depth + 1)?;
            }
        }
        if object.get("properties").is_none() {
            return Err(format!("{id}: objects require properties"));
        }
    }
    if types.contains(&"array") {
        if object.get("maxItems").and_then(Value::as_u64).is_none() {
            return Err(format!("{id}: arrays require maxItems"));
        }
        validate_schema(
            id,
            object
                .get("items")
                .ok_or_else(|| format!("{id}: arrays require items"))?,
            depth + 1,
        )?;
    }
    if types.contains(&"string") && object.get("maxLength").and_then(Value::as_u64).is_none() {
        return Err(format!("{id}: strings require maxLength"));
    }
    if types
        .iter()
        .any(|kind| matches!(*kind, "integer" | "number"))
        && (object.get("minimum").and_then(Value::as_f64).is_none()
            || object.get("maximum").and_then(Value::as_f64).is_none())
    {
        return Err(format!("{id}: numeric schemas require minimum and maximum"));
    }
    Ok(())
}

fn string<'a>(object: &'a Map<String, Value>, field: &str) -> Result<&'a str, String> {
    object
        .get(field)
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .ok_or_else(|| format!("`{field}` must be a non-empty string"))
}

fn validate_string_array(
    id: &str,
    object: &Map<String, Value>,
    field: &str,
    maximum: usize,
) -> Result<(), String> {
    let values = object[field]
        .as_array()
        .ok_or_else(|| format!("{id}: {field} must be an array"))?;
    let mut seen = HashSet::new();
    if values.len() > maximum
        || values.iter().any(|value| {
            value
                .as_str()
                .filter(|value| !value.is_empty())
                .is_none_or(|value| !seen.insert(value))
        })
    {
        return Err(format!("{id}: {field} is invalid or unbounded"));
    }
    Ok(())
}

fn valid_id(id: &str) -> bool {
    let Some((domain, action)) = id.split_once('.') else {
        return false;
    };
    !domain.is_empty()
        && !action.is_empty()
        && id.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'.' || byte == b'_'
        })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn catalog() -> Value {
        serde_json::from_str(include_str!("../../capabilities/catalog.json")).unwrap()
    }

    fn record_mut<'a>(catalog: &'a mut Value, id: &str) -> &'a mut Value {
        catalog
            .as_array_mut()
            .unwrap()
            .iter_mut()
            .find(|record| record["id"] == id)
            .unwrap()
    }

    #[test]
    fn catalog_runtime_metadata_is_strict() {
        assert_eq!(validate_catalog(&catalog()).unwrap(), 55);
        for (field, value) in [
            ("idempotency", json!("retry-everything")),
            ("saveBehavior", json!("automatic")),
            ("transactionBehavior", json!("best-effort")),
            ("reversibility", json!("maybe")),
        ] {
            let mut invalid = catalog();
            record_mut(&mut invalid, "actor.spawn")[field] = value;
            assert!(
                validate_catalog(&invalid).is_err(),
                "accepted invalid {field}"
            );
        }
    }

    #[test]
    fn catalogued_mutations_have_complete_runtime_routes() {
        let catalog = catalog();
        let mutations = catalog
            .as_array()
            .unwrap()
            .iter()
            .filter(|record| record["mutates"] == true)
            .count();
        assert_eq!(mutations, 33);
        assert!(validate_catalog(&catalog).is_ok());

        let mut missing_target = catalog.clone();
        record_mut(&mut missing_target, "actor.spawn")["verification"]
            .as_object_mut()
            .unwrap()
            .remove("targetFields");
        assert!(validate_catalog(&missing_target).is_err());
    }

    #[test]
    fn compile_failure_contract_requires_non_atomic_metadata() {
        let mut invalid = catalog();
        record_mut(&mut invalid, "blueprint.compile")["transactionBehavior"] = json!("atomic");
        assert!(validate_catalog(&invalid).is_err());
    }

    #[test]
    fn generated_runtime_metadata_matches_catalog_field_for_field() {
        let catalog = catalog();
        for record in catalog.as_array().unwrap() {
            let id = record["id"].as_str().unwrap();
            let metadata = magi_unreal_axi::capability::capability_metadata(id).unwrap();
            let verification = record["verification"].as_object().unwrap();
            assert_eq!(metadata.execution, record["execution"]);
            assert_eq!(metadata.mutates, record["mutates"]);
            assert_eq!(metadata.destructive, record["destructive"]);
            assert_eq!(metadata.idempotency, record["idempotency"]);
            assert_eq!(metadata.save_behavior, record["saveBehavior"]);
            assert_eq!(metadata.transaction_behavior, record["transactionBehavior"]);
            assert_eq!(metadata.reversibility, record["reversibility"]);
            assert_eq!(
                metadata.allowed_editor_states,
                string_values(&record["allowedEditorStates"])
            );
            assert_eq!(
                metadata.required_modules,
                string_values(&record["requiresModules"])
            );
            assert_eq!(
                metadata.readback,
                verification.get("readback").and_then(Value::as_str)
            );
            assert_eq!(
                metadata.target_fields,
                verification
                    .get("targetFields")
                    .map(string_values)
                    .unwrap_or_default()
            );
            assert_eq!(
                metadata.failure_receipt,
                verification.get("failureReceipt").and_then(Value::as_str)
            );
        }
    }
}

